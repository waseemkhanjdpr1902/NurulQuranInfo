import assert from "node:assert/strict";
import React, { act } from "react";
import { JSDOM } from "jsdom";

const unwrap = mod => mod.default && typeof mod.default === "object" ? mod.default : mod;
const { validMushafPage, mushafSourceUrl, MUSHAF_STORAGE_KEY } = unwrap(await import("../src/lib/mushaf.ts"));
for (const invalid of [null, "", "0", 0, -1, 605, "1.5", 1.5, "2x", Infinity]) assert.equal(validMushafPage(invalid), null);
assert.equal(validMushafPage("604"), 604);
assert.equal(mushafSourceUrl(1), "https://quran.ksu.edu.sa/png_big/1.png");
const { GET } = unwrap(await import("../src/app/api/mushaf/[page]/route.ts"));
let requests = 0;
const bytes = new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10]);
globalThis.fetch = async url => {
  requests++;
  assert.equal(url, "https://quran.ksu.edu.sa/png_big/604.png");
  return new Response(bytes, { headers: { "content-type": "image/png" } });
};
const get = page => GET(new Request("https://example.test/api/mushaf/" + page), { params: Promise.resolve({page}) });
assert.equal((await get("605")).status, 400);
assert.equal(requests, 0);
const response = await get("604");
assert.deepEqual(new Uint8Array(await response.arrayBuffer()), bytes, "publisher image forwarded unchanged");
globalThis.fetch = async () => new Response("not an image", {headers: {"content-type": "text/html"}});
assert.equal((await get("1")).status, 502);
globalThis.fetch = async () => { throw new Error("network"); };
assert.equal((await get("1")).status, 502);

const dom = new JSDOM('<div id="root"></div>', { url: "https://example.test/mushaf?page=604", pretendToBeVisual:true });
Object.assign(globalThis, {window:dom.window, self:dom.window, document:dom.window.document, HTMLElement:dom.window.HTMLElement, Element:dom.window.Element, React, IS_REACT_ACT_ENVIRONMENT:true});
Object.defineProperty(globalThis,"navigator",{value:dom.window.navigator, configurable:true});
Object.defineProperty(globalThis,"localStorage",{value:dom.window.localStorage, configurable:true});
dom.window.HTMLElement.prototype.scrollTo = () => {};
const { createRoot } = await import("react-dom/client");
const { UILanguageProvider } = unwrap(await import("../src/components/UILanguageProvider.tsx"));
const readerModule = await import("../src/components/MushafReader.tsx");
const Reader = readerModule.default.default || readerModule.default;
let root = createRoot(document.getElementById("root"));
const render = () => act(async()=>root.render(React.createElement(UILanguageProvider,null,React.createElement(Reader))));
await render();
assert.ok(new URL(document.querySelector("img").getAttribute("src"),window.location.href).pathname.startsWith("/api/mushaf/604"));
const find = text => [...document.querySelectorAll("button")].find(b=>b.textContent===text);
assert.ok(find("Next page").disabled);
await act(async()=>find("Previous page").click());
assert.ok(new URL(document.querySelector("img").getAttribute("src"),window.location.href).pathname.startsWith("/api/mushaf/603"));
await act(async()=>document.querySelector('[aria-label="Zoom in"]').click());
assert.equal(JSON.parse(localStorage.getItem(MUSHAF_STORAGE_KEY)).zoom,125);
await act(async()=>document.querySelector("img").dispatchEvent(new dom.window.Event("error")));
assert.ok(find("Retry"));
await act(async()=>find("Retry").click());
assert.ok(document.querySelector("img").getAttribute("src").includes("retry=1"));
await act(async()=>{
 const select=document.querySelector('select[aria-label="Choose surah"]'); select.value="112"; select.dispatchEvent(new dom.window.Event("change",{bubbles:true}));
});
assert.equal(document.querySelector('select[aria-label="Choose surah"]').value,"112");
assert.ok(new URL(document.querySelector("img").getAttribute("src"),window.location.href).pathname.startsWith("/api/mushaf/604"));
await act(async()=>root.unmount());
window.history.replaceState(null,"","/mushaf");
root=createRoot(document.getElementById("root"));
await render();
assert.ok(new URL(document.querySelector("img").getAttribute("src"),window.location.href).pathname.startsWith("/api/mushaf/604"),"saved page restored");
assert.equal(document.querySelector('[aria-label="Zoom level"]').textContent,"125%");
await act(async()=>root.unmount());
console.log("Mushaf: page limits, unchanged image proxy, network recovery, navigation, zoom and saved position passed.");
