import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import React, {act} from 'react';
const dom = new JSDOM('<div id="root"></div>', {url:'https://example.test/',pretendToBeVisual:true});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,HTMLElement:dom.window.HTMLElement,Element:dom.window.Element,SVGElement:dom.window.SVGElement,React,IS_REACT_ACT_ENVIRONMENT:true,getComputedStyle:dom.window.getComputedStyle});
Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true});
Object.defineProperty(globalThis,'localStorage',{value:dom.window.localStorage,configurable:true});
class Observer {observe(){} unobserve(){} disconnect(){}}
globalThis.IntersectionObserver=dom.window.IntersectionObserver=Observer;
window.matchMedia=()=>({matches:false,addListener(){},removeListener(){},addEventListener(){},removeEventListener(){}});
Object.defineProperty(navigator,'clipboard',{value:{writeText:async value=>{globalThis.copied=value;}}});
const {createRoot}=await import('react-dom/client');
const {AppRouterContext}=await import('next/dist/shared/lib/app-router-context.shared-runtime.js');
const unwrap=m=>m.default?.default || m.default || m;
const {UILanguageProvider}=await import('../src/components/UILanguageProvider.tsx');
const {PrayerTimesProvider}=await import('../src/components/PrayerTimesProvider.tsx');
const root=createRoot(document.getElementById('root'));
const router={push(){},replace(){},back(){},forward(){},prefetch(){},refresh(){}};
const render=async Component=>act(async()=>root.render(React.createElement(AppRouterContext.Provider,{value:router},React.createElement(UILanguageProvider,null,React.createElement(PrayerTimesProvider,null,React.createElement(Component))))));
const click=async selector=>act(async()=>document.querySelector(selector).click());
const Tasbih=unwrap(await import('../src/app/tasbih/page.tsx'));
await render(Tasbih);
await click('[aria-label="Count dhikr"]');
assert.equal(JSON.parse(localStorage.getItem('nurulquran.tasbih.v1')).count,1);
await click('nav a');
assert.equal(JSON.parse(localStorage.getItem('nurulquran.tasbih.v1')).count,1,'navigation must not count dhikr');
await click('[aria-label="Reset session count"]');
assert.equal(JSON.parse(localStorage.getItem('nurulquran.tasbih.v1')).count,0);
assert.equal(JSON.parse(localStorage.getItem('nurulquran.tasbih.v1')).totalCount,1);
const Dua=unwrap(await import('../src/app/dua/page.tsx'));
await render(Dua);
await click('[aria-label="Copy dua"]');
assert.match(globalThis.copied,/Abu Dawud/);
await click('[aria-label="Favourite dua"]');
assert.deepEqual(JSON.parse(localStorage.getItem('nurulquran.dua-favourites.v1')),[1]);
await render(()=>null); await render(Dua);
assert.equal(document.querySelector('[aria-label="Favourite dua"]').getAttribute('aria-pressed'),'true');
await click('[aria-label="Share dua"]');
assert.match(globalThis.copied,/Final Return/);
const Zakat=unwrap(await import('../src/app/zakat/page.tsx'));
await render(Zakat);
assert.equal(document.querySelector('[aria-label="Current gold price per gram"]').value,'');
assert.match(document.body.textContent,/No payment is collected here/);
assert.doesNotMatch(document.body.textContent,/Pay Zakat Now/);
await act(async()=>root.unmount());
console.log('PASS: tasbih counts only deliberate taps, reset preserves lifetime; dua copy, share fallback and favourite persistence; Zakat starts without invented prices or payment controls.');
