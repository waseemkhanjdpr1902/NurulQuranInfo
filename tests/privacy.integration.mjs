import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import React, { act } from 'react';
const dom = new JSDOM('<div id="root"></div>', { url: 'https://www.nurulquran.info/privacy' });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage, location: dom.window.location, CustomEvent: dom.window.CustomEvent, React, IS_REACT_ACT_ENVIRONMENT: true });
const unwrap = mod => mod.default && typeof mod.default === 'object' ? mod.default : mod;
const privacy = unwrap(await import('../src/lib/privacy.ts'));
assert.equal(privacy.readAnalyticsConsent(), null);
privacy.setAnalyticsConsent('granted');
assert.equal(window['ga-disable-' + privacy.ANALYTICS_ID], false);
document.cookie = '_ga=example; Path=/';
privacy.setAnalyticsConsent('denied');
assert.equal(window['ga-disable-' + privacy.ANALYTICS_ID], true);
assert.equal(document.cookie.includes('_ga='), false);
assert.equal(privacy.readAnalyticsConsent(), 'denied');
const draft = privacy.deletionEmail(' reader@example.com ', 'account');
assert.ok(draft.href.startsWith('mailto:support@nurulquran.info?'));
assert.ok(decodeURIComponent(draft.href).includes('Account email: reader@example.com'));
assert.ok(privacy.deletionEmail('', 'data').body.includes('while keeping my account'));
localStorage.setItem('nurulquran.journey.v1', 'private');
localStorage.setItem('nurulquran.reflections.v1', 'private');
localStorage.setItem('nurulquran.mushaf.indopak.v1', 'private');
localStorage.setItem('sb-auth-token', 'keep');
localStorage.setItem('unrelated', 'keep');
const removedCaches = [];
const caches = { keys: async () => ['nurulquran-pages', 'other-app'], delete: async name => { removedCaches.push(name); return true; } };
Object.assign(globalThis, { caches }); Object.assign(window, { caches });
const { createRoot } = await import('react-dom/client');
const choicesModule = await import('../src/components/PrivacyChoices.tsx');
const Choices = choicesModule.default.default || choicesModule.default;
const root = createRoot(document.getElementById('root'));
await act(async () => root.render(React.createElement(Choices)));
const clear = [...document.querySelectorAll('button')].find(el => el.textContent === 'Clear local reading data');
assert.equal(clear.disabled, true);
await act(async () => document.querySelector('input[type=checkbox]').click());
await act(async () => clear.click());
assert.equal(localStorage.getItem('nurulquran.reflections.v1'), null);
assert.equal(localStorage.getItem('nurulquran.journey.v1'), null);
assert.equal(localStorage.getItem('nurulquran.mushaf.indopak.v1'), null);
assert.equal(localStorage.getItem('sb-auth-token'), 'keep');
assert.equal(localStorage.getItem('unrelated'), 'keep');
assert.deepEqual(removedCaches, ['nurulquran-pages']);
assert.match(document.querySelector('[role=status]').textContent, /cloud data were not deleted/);
await act(async () => root.unmount());
console.log('Privacy consent, email draft and scoped local deletion checks passed.');
