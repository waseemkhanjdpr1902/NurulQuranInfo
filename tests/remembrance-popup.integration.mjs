import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import React, { act } from 'react';
const dom = new JSDOM('<div id="root"></div>', { url: 'https://example.test/', pretendToBeVisual: true });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, Element: dom.window.Element, SVGElement: dom.window.SVGElement, React, IS_REACT_ACT_ENVIRONMENT: true, getComputedStyle: dom.window.getComputedStyle });
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
Object.defineProperty(globalThis, 'localStorage', { value: dom.window.localStorage, configurable: true });
Object.defineProperty(window, 'isSecureContext', { value: true });
let sent = [];
const registration = { showNotification: async (title, options) => { sent.push({ title, options }); } };
Object.defineProperty(navigator, 'serviceWorker', { value: { register: async () => registration, ready: Promise.resolve(registration) }, configurable: true });
const NotificationMock = { permission: 'default', requestPermission: async () => { NotificationMock.permission = 'granted'; return 'granted'; } };
window.Notification = globalThis.Notification = NotificationMock;
const { createRoot } = await import('react-dom/client');
const mod = await import('../src/components/RemembrancePopup.tsx');
const Popup = mod.default.default || mod.default;
let root = createRoot(document.getElementById('root'));
await act(async () => root.render(React.createElement(Popup)));
assert.ok(document.querySelector('[role="dialog"]'), 'name appears on opening');
assert.equal(sent.length, 0, 'notification requires opt-in');
const enable = [...document.querySelectorAll('button')].find(b => b.textContent.includes('Enable phone reminders'));
await act(async () => { enable.click(); await new Promise(r => setTimeout(r, 0)); });
assert.equal(sent.length, 1);
assert.ok(sent[0].options.body);
assert.equal(localStorage.getItem('nurulquran.name-reminder-enabled'), 'true');
assert.equal(sent[0].options.tag, 'nurulquran-name-reminder');
await act(async () => root.unmount());
root = createRoot(document.getElementById('root'));
await act(async () => { root.render(React.createElement(Popup)); await new Promise(r => setTimeout(r, 0)); });
assert.equal(sent.length, 2, 'enabled reminder sends on next opening');
const disable = [...document.querySelectorAll('button')].find(b => b.textContent.includes('Turn off phone reminders'));
await act(async () => disable.click());
assert.equal(localStorage.getItem('nurulquran.name-reminder-enabled'), null);
await act(async () => root.unmount());
console.log('PASS: opening card, opt-in, notification content, next opening, and disable.');
