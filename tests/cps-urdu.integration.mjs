import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
const dom = new JSDOM('<div id="root"></div>', { url: 'https://example.test' });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, React, IS_REACT_ACT_ENVIRONMENT: true, localStorage: dom.window.localStorage });
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
let paused = [];
let loads = 0;
dom.window.HTMLMediaElement.prototype.pause = function () { paused.push(this.src); };
dom.window.HTMLMediaElement.prototype.load = function () { loads++; };
const mod = await import('../src/components/CPSUrduPlayer.tsx');
const Player = mod.default.default || mod.default;
const lang = await import('../src/components/UILanguageProvider.tsx');
const { UILanguageProvider } = lang.default || lang;
const data = await import('../src/data/cps-urdu-audio.ts');
const { CPS_AUDIO_PATHS, cpsUrduAudioUrl } = data.default || data;
assert.equal(CPS_AUDIO_PATHS.length, 114);
assert.equal(new Set(CPS_AUDIO_PATHS).size, 114);
for (let i = 1; i <= 114; i++) {
  const url = new URL(cpsUrduAudioUrl(i));
  assert.equal(url.protocol, 'https:');
  assert.equal(url.hostname, 'huggingface.co');
  assert.ok(decodeURIComponent(url.pathname).endsWith(CPS_AUDIO_PATHS[i - 1]));
}
for (const value of [0, 115, 1.5, NaN]) assert.equal(cpsUrduAudioUrl(value), null);
const root = createRoot(document.getElementById('root'));
const render = (n, name) => act(async () => root.render(React.createElement(UILanguageProvider, null, React.createElement(Player, { key: n, surahNumber: n, surahName: name }))));
await render(1, 'Al-Fatiha');
assert.equal(document.querySelector('iframe'), null);
let audio = document.querySelector('audio');
assert.equal(audio.src, cpsUrduAudioUrl(1));
assert.equal(audio.preload, 'none');
assert.ok(audio.controls);
assert.match(document.body.textContent, /Khalid Syed/);
await act(async () => audio.dispatchEvent(new dom.window.Event('error')));
assert.match(document.querySelector('[role="alert"]').textContent, /could not load/);
await act(async () => document.querySelector('button').click());
assert.equal(loads, 1);
assert.equal(document.querySelector('[role="alert"]'), null);
await render(18, 'Al-Kahf');
assert.ok(paused.includes(cpsUrduAudioUrl(1)), 'Switching surah stops previous playback');
assert.equal(document.querySelector('audio').src, cpsUrduAudioUrl(18));
await act(async () => root.unmount());
assert.ok(paused.includes(cpsUrduAudioUrl(18)), 'Leaving the mode stops playback');
console.log('PASS: 114 unique surah URLs, native controls, lazy audio, retry, surah change and unmount cleanup.');
